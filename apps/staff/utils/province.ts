const NAMES = Object.keys(PROVINCE_CODE).sort((a, b) => b.length - a.length)

/** ตัวย่อจังหวัดจากข้อความ (ชื่อสาขา/ที่อยู่) เช่น "สาขาสุรินทร์" → "SRN" · ไม่พบ = null */
export function provinceAbbr(...texts: Array<string | null | undefined>): string | null {
  for (const t of texts) {
    if (!t) continue
    const hit = NAMES.find((n) => t.includes(n))
    if (hit) return PROVINCE_CODE[hit]!
  }
  return null
}
